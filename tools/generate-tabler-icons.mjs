// Regenerates the Tabler icon enums and glyph tables used by CrabDesk.
//
// Usage (from the repository root):
//   node tools/generate-tabler-icons.mjs
//   node tools/generate-tabler-icons.mjs --version 3.51.0
//   node tools/generate-tabler-icons.mjs --check
//
// The script downloads the @tabler/icons-webfont tarball, reads tabler-icons.css
// to map icon names to codepoints, copies the TTF next to the runtime assets, and
// rewrites the generated C# files. It needs Node 20+ and `tar` on PATH.
//
// `--check` regenerates into a temporary folder and fails when the checked-in
// files differ, so CI can detect a stale glyph table.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const DEFAULT_VERSION = "3.51.0";
const ROOT = path.resolve(import.meta.dirname, "..");

const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const versionIndex = args.indexOf("--version");
const version = versionIndex >= 0 && args[versionIndex + 1] ? args[versionIndex + 1] : DEFAULT_VERSION;

const fontTarget = path.join(ROOT, "CrabDesk.Runtime", "Assets", "tabler-icons.ttf");
const enumTarget = path.join(ROOT, "CrabDesk.WinUI", "Controls", "TablerIconName.cs");
const glyphTarget = path.join(ROOT, "CrabDesk.WinUI", "Controls", "TablerGlyphs.cs");

const workDir = fs.mkdtempSync(path.join(os.tmpdir(), "crabdesk-tabler-"));

if (!/^[0-9A-Za-z.\-]+$/.test(version)) throw new Error(`Unsupported version "${version}".`);

function run(command, commandArgs, options = {}) {
  return execFileSync(command, commandArgs, { stdio: "inherit", ...options });
}

async function downloadTarball() {
  const metadata = await fetch(`https://registry.npmjs.org/@tabler/icons-webfont/${version}`);
  if (!metadata.ok) throw new Error(`Registry lookup failed: ${metadata.status} ${metadata.statusText}`);
  const { dist } = await metadata.json();
  if (!dist?.tarball) throw new Error(`No tarball published for @tabler/icons-webfont ${version}.`);

  const tarball = await fetch(dist.tarball);
  if (!tarball.ok) throw new Error(`Tarball download failed: ${tarball.status} ${tarball.statusText}`);
  const archive = path.join(workDir, "tabler-icons-webfont.tgz");
  fs.writeFileSync(archive, Buffer.from(await tarball.arrayBuffer()));
  return archive;
}

console.log(`Preparing Tabler Icons ${version} in ${workDir}`);
run("tar", ["-xzf", await downloadTarball()], { cwd: workDir });

const packageDir = path.join(workDir, "package");
const css = fs.readFileSync(path.join(packageDir, "dist", "tabler-icons.css"), "utf8");
const fontPath = path.join(packageDir, "dist", "fonts", "tabler-icons.ttf");
const licensePath = path.join(packageDir, "LICENSE");

/** Maps the kebab-case Tabler name to its font codepoint. */
const icons = new Map();
for (const match of css.matchAll(/^\.ti-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-fA-F]+)";/gm)) {
  const name = match[1];
  if (!icons.has(name)) icons.set(name, Number.parseInt(match[2], 16));
}
if (icons.size < 1000) throw new Error(`Only parsed ${icons.size} icons from tabler-icons.css.`);

const CSharpKeywords = new Set(
  ("abstract as base bool break byte case catch char checked class const continue decimal default delegate do double " +
    "else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is " +
    "lock long namespace new null object operator out override params private protected public readonly ref return sbyte " +
    "sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe " +
    "ushort using virtual void volatile while").split(" "),
);

/** Converts `arrow-down-to-line` to `ArrowDownToLine`. */
function toPascalCase(name) {
  let identifier = name
    .split("-")
    .map((part) => (part.length === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");
  if (/^[0-9]/.test(identifier)) identifier = `Icon${identifier}`;
  if (CSharpKeywords.has(identifier.toLowerCase())) identifier += "Icon";
  return identifier;
}

const members = [];
const seen = new Set(["None"]);
for (const [name, codePoint] of icons) {
  const identifier = toPascalCase(name);
  if (seen.has(identifier)) throw new Error(`Duplicate C# identifier for Tabler icon "${name}": ${identifier}`);
  seen.add(identifier);
  members.push({ name, identifier, codePoint });
}
members.sort((a, b) => (a.identifier < b.identifier ? -1 : a.identifier > b.identifier ? 1 : 0));

const enumLines = [];
enumLines.push("// <auto-generated>");
enumLines.push("//     Generated by tools/generate-tabler-icons.mjs. Do not edit by hand.");
enumLines.push(`//     Source: @tabler/icons-webfont ${version} (tabler-icons.css).`);
enumLines.push("// </auto-generated>");
enumLines.push("");
enumLines.push("namespace CrabDesk.WinUI.Controls;");
enumLines.push("");
enumLines.push("/// <summary>");
enumLines.push("/// Tabler outline icons. Each member carries the icon's font codepoint so the");
enumLines.push("/// glyph lookup is a cast instead of a multi-thousand-case switch. The trailing");
enumLines.push("/// comment on each member is the upstream Tabler icon name.");
enumLines.push("/// </summary>");
enumLines.push("public enum TablerIconName");
enumLines.push("{");
enumLines.push("    None = 0,");
for (const member of members) {
  enumLines.push(`    ${member.identifier} = 0x${member.codePoint.toString(16).toUpperCase()}, // ${member.name}`);
}
enumLines.push("}");

const glyphLines = [];
glyphLines.push("// <auto-generated>");
glyphLines.push("//     Generated by tools/generate-tabler-icons.mjs. Do not edit by hand.");
glyphLines.push(`//     Source: @tabler/icons-webfont ${version} (tabler-icons.css).`);
glyphLines.push("// </auto-generated>");
glyphLines.push("");
glyphLines.push("using System;");
glyphLines.push("using System.Linq;");
glyphLines.push("");
glyphLines.push("namespace CrabDesk.WinUI.Controls;");
glyphLines.push("");
glyphLines.push("/// <summary>");
glyphLines.push("/// Resolves Tabler icons to the strings consumed by the icon font.");
glyphLines.push("/// </summary>");
glyphLines.push("public static class TablerGlyphs");
glyphLines.push("{");
glyphLines.push("    /// <summary>Converts an icon to its UTF-16 glyph string.</summary>");
glyphLines.push("    public static string ToGlyph(TablerIconName icon) =>");
glyphLines.push("        icon == TablerIconName.None ? string.Empty : char.ConvertFromUtf32((int)icon);");
glyphLines.push("");
glyphLines.push("    /// <summary>");
glyphLines.push("    /// Resolves an icon by its Tabler name (<c>arrow-down-to-line</c> or");
glyphLines.push("    /// <c>ArrowDownToLine</c>). Used for icon names that arrive as strings.");
glyphLines.push("    /// </summary>");
glyphLines.push("    public static bool TryGetGlyph(string iconName, out string glyph)");
glyphLines.push("    {");
glyphLines.push("        if (!string.IsNullOrWhiteSpace(iconName) && TryParse(iconName, out var icon))");
glyphLines.push("        {");
glyphLines.push("            glyph = ToGlyph(icon);");
glyphLines.push("            return glyph.Length > 0;");
glyphLines.push("        }");
glyphLines.push("");
glyphLines.push("        glyph = string.Empty;");
glyphLines.push("        return false;");
glyphLines.push("    }");
glyphLines.push("");
glyphLines.push("    private static bool TryParse(string iconName, out TablerIconName icon)");
glyphLines.push("    {");
glyphLines.push("        var trimmed = iconName.Trim();");
glyphLines.push("        if (Enum.TryParse(trimmed, ignoreCase: true, out icon) && Enum.IsDefined(icon) && icon != TablerIconName.None)");
glyphLines.push("        {");
glyphLines.push("            return true;");
glyphLines.push("        }");
glyphLines.push("");
glyphLines.push("        // Accept the kebab-case Tabler name so persisted or reflected names keep working.");
glyphLines.push("        var pascal = string.Concat(trimmed");
glyphLines.push("            .Split('-', StringSplitOptions.RemoveEmptyEntries)");
glyphLines.push("            .Select(part => char.ToUpperInvariant(part[0]) + part[1..]));");
glyphLines.push("        return Enum.TryParse(pascal, ignoreCase: true, out icon) && Enum.IsDefined(icon);");
glyphLines.push("    }");
glyphLines.push("}");

// .gitattributes pins *.cs to CRLF, so the generated files match that.
const newline = "\r\n";
const enumText = enumLines.join(newline) + newline;
const glyphText = glyphLines.join(newline) + newline;

const sameText = (left, right) => left.replace(/\r\n/g, "\n") === right.replace(/\r\n/g, "\n");

if (checkOnly) {
  const failures = [];
  if (!sameText(fs.readFileSync(enumTarget, "utf8"), enumText)) failures.push(enumTarget);
  if (!sameText(fs.readFileSync(glyphTarget, "utf8"), glyphText)) failures.push(glyphTarget);
  if (failures.length > 0) {
    console.error("Generated Tabler files are stale:\n" + failures.map((file) => `  ${file}`).join("\n"));
    process.exit(1);
  }
  console.log("Generated Tabler files are up to date.");
} else {
  fs.mkdirSync(path.dirname(fontTarget), { recursive: true });
  fs.copyFileSync(fontPath, fontTarget);
  fs.copyFileSync(licensePath, path.join(ROOT, "licenses", "Tabler-Icons-LICENSE.txt"));
  fs.writeFileSync(enumTarget, enumText);
  fs.writeFileSync(glyphTarget, glyphText);
  console.log(`Wrote ${members.length} icons to ${path.relative(ROOT, enumTarget)}`);
  console.log(`Wrote glyph table to ${path.relative(ROOT, glyphTarget)}`);
  console.log(`Wrote font to ${path.relative(ROOT, fontTarget)}`);
}

fs.rmSync(workDir, { recursive: true, force: true });
