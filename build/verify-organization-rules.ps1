param(
    [string]$Executable = "..\artifacts\publish\win-x64\CrabDesk.WinUI.exe"
)

$ErrorActionPreference = "Stop"
$exe = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot $Executable))
if (-not (Test-Path -LiteralPath $exe)) {
    throw "CrabDesk executable not found: $exe"
}
if (@(Get-Process CrabDesk.WinUI -ErrorAction SilentlyContinue).Count -gt 0) {
    throw "Close the running CrabDesk instance before verifying organization rules."
}

$testId = [Guid]::NewGuid().ToString("N")
$testRoot = Join-Path ([System.IO.Path]::GetTempPath()) ("CrabDesk.RuleTest." + $testId)
$desktop = [Environment]::GetFolderPath([Environment+SpecialFolder]::DesktopDirectory)
$desktopFile = Join-Path $desktop ("CrabDeskRuleTest-" + $testId + ".crabrule")
$desktopLiveFile = Join-Path $desktop ("CrabDeskRuleLiveTest-" + $testId + ".crablive")
$desktopDocFile = Join-Path $desktop ("CrabDeskRuleDocTest-" + $testId + ".txt")
[System.IO.Directory]::CreateDirectory($testRoot) | Out-Null
[System.IO.File]::WriteAllText($desktopFile, "CrabDesk organization rule integration test")
[System.IO.File]::WriteAllText($desktopDocFile, "CrabDesk auto box position integration test")

$previousDataDirectory = $env:CRABDESK_DATA_DIR
$env:CRABDESK_DATA_DIR = $testRoot
$sourceBoxId = [Guid]::NewGuid()
$targetBoxId = [Guid]::NewGuid()
$ruleId = [Guid]::NewGuid()
$docRuleId = [Guid]::NewGuid()
$config = @{
    SchemaVersion = 18
    Settings = @{
        TakeOverDesktop = $true
        ShowSystemItems = $false
        ConfirmDeleteBox = $true
        ThemeMode = 0
        DesktopBehavior = @{
            RefreshAfterRename = $false
        }
    }
    Organization = @{
        Enabled = $true
        RunOnStartup = $true
        RunOnDesktopChanges = $true
        ReassignExistingItems = $false
    }
    OrganizationRules = @(
        @{
            Id = $ruleId
            Title = "CrabDesk 测试规则"
            Enabled = $true
            Priority = 10
            ItemKinds = @(0)
            NamePattern = "*"
            Extensions = @("crabrule", "crablive")
            Action = 0
            TargetBoxId = $targetBoxId
        },
        @{
            Id = $docRuleId
            BuiltInId = "documents"
            Title = "文档"
            Enabled = $true
            Priority = 20
            ItemKinds = @(0)
            NamePattern = "*"
            Extensions = @("txt")
            Action = 0
        }
    )
    Boxes = @(
        @{
            Id = $sourceBoxId
            Title = "常用"
            MonitorId = "primary"
            Bounds = @{ X = 40; Y = 50; Width = 420; Height = 300 }
        },
        @{
            Id = $targetBoxId
            Title = "规则目标"
            MonitorId = "primary"
            Bounds = @{ X = 500; Y = 50; Width = 360; Height = 280 }
        }
    )
    Assignments = @{}
}
$config | ConvertTo-Json -Depth 10 | Set-Content -LiteralPath (Join-Path $testRoot "config.json") -Encoding UTF8

$process = $null
try {
    $process = Start-Process -FilePath $exe -PassThru
    Start-Sleep -Seconds 8
    if ($process.HasExited) {
        throw "CrabDesk exited before applying startup organization rules."
    }
    [System.IO.File]::WriteAllText($desktopLiveFile, "CrabDesk realtime organization rule integration test")
    Start-Sleep -Seconds 4
    $exitCommand = Start-Process -FilePath $exe -ArgumentList "--exit-existing" -Wait -PassThru
    if ($exitCommand.ExitCode -ne 0) {
        throw "The organization-rules exit command returned code $($exitCommand.ExitCode)."
    }
    if (-not $process.WaitForExit(10000)) {
        throw "CrabDesk did not exit after the rule test."
    }

    $saved = Get-Content -LiteralPath (Join-Path $testRoot "config.json") -Raw -Encoding UTF8 | ConvertFrom-Json
    $assignments = @($saved.Assignments.PSObject.Properties | ForEach-Object { [PSCustomObject]@{ Key = $_.Name; BoxId = [Guid]$_.Value } })
    $targetAssignments = @($assignments | Where-Object { $_.BoxId -eq $targetBoxId })
    if ($targetAssignments.Count -ne 2) {
        $assignmentDump = ($saved.Assignments | ConvertTo-Json -Compress)
        throw "Startup and realtime rules did not assign both test desktop items to the target box. Count=$($targetAssignments.Count), Assignments=$assignmentDump"
    }
    Write-Host "Startup and realtime organization rules assigned both matching desktop items."

    $docRules = @($saved.OrganizationRules | Where-Object { $_.BuiltInId -eq "documents" })
    if ($docRules.Count -lt 1) {
        throw "The built-in documents rule was not persisted after organization."
    }
    $autoBoxes = @($saved.Boxes | Where-Object { $_.IsAutoGenerated -eq $true })
    if ($autoBoxes.Count -lt 1) {
        throw "Expected an auto-generated box for the documents rule after organization."
    }
    $autoBox = $autoBoxes[0]
    $movedX = 300.0
    $movedY = 420.0
    $autoBox.Bounds.X = $movedX
    $autoBox.Bounds.Y = $movedY
    $saved | ConvertTo-Json -Depth 10 | Set-Content -LiteralPath (Join-Path $testRoot "config.json") -Encoding UTF8

    $process = Start-Process -FilePath $exe -PassThru
    Start-Sleep -Seconds 8
    if ($process.HasExited) {
        throw "CrabDesk exited before the second organization run."
    }
    $exitCommand = Start-Process -FilePath $exe -ArgumentList "--exit-existing" -Wait -PassThru
    if ($exitCommand.ExitCode -ne 0) {
        throw "The position-check exit command returned code $($exitCommand.ExitCode)."
    }
    if (-not $process.WaitForExit(10000)) {
        throw "CrabDesk did not exit after the position check."
    }

    $savedAfter = Get-Content -LiteralPath (Join-Path $testRoot "config.json") -Raw -Encoding UTF8 | ConvertFrom-Json
    $boxAfter = @($savedAfter.Boxes | Where-Object { $_.Id -eq $autoBox.Id })[0]
    if ($null -eq $boxAfter) {
        throw "The auto-generated box disappeared after the second organization run."
    }
    if ([double]$boxAfter.Bounds.X -ne $movedX -or [double]$boxAfter.Bounds.Y -ne $movedY) {
        throw "Auto-generated box position was reset after organization. Expected ($movedX,$movedY), got ($($boxAfter.Bounds.X),$($boxAfter.Bounds.Y))."
    }
    Write-Host "Organization preserved the manually moved auto-generated box position."
}
finally {
    if ($process -and -not $process.HasExited) {
        Stop-Process -Id $process.Id -Force -ErrorAction SilentlyContinue
    }
    Remove-Item -LiteralPath $desktopFile -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $desktopLiveFile -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $desktopDocFile -Force -ErrorAction SilentlyContinue
    if ($null -eq $previousDataDirectory) {
        Remove-Item Env:\CRABDESK_DATA_DIR -ErrorAction SilentlyContinue
    }
    else {
        $env:CRABDESK_DATA_DIR = $previousDataDirectory
    }
    $resolvedRoot = [System.IO.Path]::GetFullPath($testRoot)
    $tempRoot = [System.IO.Path]::GetFullPath([System.IO.Path]::GetTempPath())
    if ($resolvedRoot.StartsWith($tempRoot, [System.StringComparison]::OrdinalIgnoreCase)) {
        Remove-Item -LiteralPath $resolvedRoot -Recurse -Force -ErrorAction SilentlyContinue
    }
}

Write-Host "Organization rule integration test passed."
