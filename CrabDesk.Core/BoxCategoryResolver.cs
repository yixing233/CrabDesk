namespace CrabDesk.Core;

/// <summary>How a category name found its destination.</summary>
public enum BoxCategoryMatch
{
    /// <summary>The category equals a normal box title; the item joins the box's "全部" view.</summary>
    Title,

    /// <summary>
    /// The category equals a sub-tab title. A sub-tab is the user's own way of
    /// naming one group inside an aggregate box, so it is the same kind of
    /// destination as a box and wins over a box title of the same name.
    /// </summary>
    SubTab
}

/// <summary>
/// Where a category name lives: a box, and the child tab inside it when the
/// category names one. A null <see cref="TabId"/> means the box's unfiltered
/// "全部" view.
/// </summary>
public sealed record BoxCategoryTarget(DesktopBox Box, Guid? TabId, BoxCategoryMatch Match);

/// <summary>
/// Single source of truth for turning a category name into a destination.
/// Organizing, the AI classifier and the settings list all ask this so a name
/// can never resolve two different ways.
/// </summary>
public static class BoxCategoryResolver
{
    /// <summary>
    /// Resolves <paramref name="category"/> against the boxes in
    /// <paramref name="state"/>. Order of preference:
    /// <list type="number">
    /// <item>a sub-tab with that title, because a sub-tab is a box the user
    /// simply grouped under another one;</item>
    /// <item>the rule's explicit target box, which the user pinned;</item>
    /// <item>a box with that title.</item>
    /// </list>
    /// A sub-tab outranking the pinned box is deliberate: when a rule is
    /// pinned to the standalone "图片" box and the user then creates an
    /// "图片" sub-tab somewhere, the pinned box is exactly the duplicate that
    /// has to stop collecting. Among equally good candidates the pinned box
    /// wins, then a box an earlier organize pass generated, then list order,
    /// so the result is deterministic across runs.
    /// </summary>
    public static BoxCategoryTarget? Resolve(CrabDeskState state, string? category, Guid? preferredBoxId = null)
    {
        ArgumentNullException.ThrowIfNull(state);
        return Resolve(state.Boxes, category, preferredBoxId);
    }

    /// <summary>Same resolution over a box list, for callers that only hold the boxes.</summary>
    public static BoxCategoryTarget? Resolve(
        IReadOnlyList<DesktopBox> boxes,
        string? category,
        Guid? preferredBoxId = null)
    {
        ArgumentNullException.ThrowIfNull(boxes);
        var name = category?.Trim() ?? string.Empty;
        if (name.Length == 0)
        {
            return null;
        }

        // Mapped folders mirror a live directory; rules and the classifier must
        // not move desktop items into one.
        var normal = boxes.Where(box => !box.IsMappedFolder).ToArray();
        if (normal.Length == 0)
        {
            return null;
        }

        var tabMatches = normal.Where(box => FindTab(box, name) is not null).ToArray();
        if (tabMatches.Length > 0)
        {
            var box = Pick(tabMatches, preferredBoxId);
            return new BoxCategoryTarget(box, FindTab(box, name)!.Id, BoxCategoryMatch.SubTab);
        }

        if (preferredBoxId is { } pin && normal.FirstOrDefault(box => box.Id == pin) is { } pinned)
        {
            return new BoxCategoryTarget(pinned, null, BoxCategoryMatch.Title);
        }

        var titleMatches = normal.Where(box =>
            string.Equals(box.Title.Trim(), name, StringComparison.CurrentCultureIgnoreCase)).ToArray();
        if (titleMatches.Length == 0)
        {
            return null;
        }

        return new BoxCategoryTarget(Pick(titleMatches, preferredBoxId), null, BoxCategoryMatch.Title);
    }

    /// <summary>The sub-tab whose title is <paramref name="name"/>, if the box has one.</summary>
    public static DesktopBoxTab? FindTab(DesktopBox box, string? name)
    {
        var trimmed = name?.Trim() ?? string.Empty;
        return trimmed.Length == 0
            ? null
            : box.ManualTabs.FirstOrDefault(tab => string.Equals(
                tab.Title?.Trim(),
                trimmed,
                StringComparison.CurrentCultureIgnoreCase));
    }

    private static DesktopBox Pick(IReadOnlyList<DesktopBox> candidates, Guid? preferredBoxId)
    {
        if (preferredBoxId is { } pin && candidates.FirstOrDefault(box => box.Id == pin) is { } pinned)
        {
            return pinned;
        }

        return candidates.FirstOrDefault(box => box.IsAutoGenerated) ?? candidates[0];
    }
}
