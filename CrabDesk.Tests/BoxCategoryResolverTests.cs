using CrabDesk.Core;
using Xunit;

namespace CrabDesk.Tests;

/// <summary>
/// A child tab is how the user groups one category inside an aggregate box, so
/// it is a destination in its own right. These pin that a category name never
/// resolves to a freshly created duplicate while a box already holds it.
/// </summary>
public sealed class BoxCategoryResolverTests
{
    [Fact]
    public void CategoryNamingAChildTabResolvesToThatTab()
    {
        var tab = new DesktopBoxTab { Title = "图片" };
        var box = new DesktopBox { Title = "资料", ManualTabs = [tab] };
        var state = new CrabDeskState { Boxes = [box] };

        var target = BoxCategoryResolver.Resolve(state, "图片");

        Assert.NotNull(target);
        Assert.Same(box, target!.Box);
        Assert.Equal(tab.Id, target.TabId);
        Assert.Equal(BoxCategoryMatch.SubTab, target.Match);
    }

    [Fact]
    public void ChildTabOutranksABoxWithTheSameName()
    {
        // The user moved "图片" into a tab of "资料" and the old standalone box
        // is still around; collecting into the tab is what stops the duplicate.
        var tab = new DesktopBoxTab { Title = "图片" };
        var aggregate = new DesktopBox { Title = "资料", ManualTabs = [tab] };
        var standalone = new DesktopBox { Title = "图片" };
        var state = new CrabDeskState { Boxes = [standalone, aggregate] };

        var target = BoxCategoryResolver.Resolve(state, "图片");

        Assert.Same(aggregate, target!.Box);
        Assert.Equal(tab.Id, target.TabId);
    }

    [Fact]
    public void LegacyGeneratedBoxLosesToAChildTabOfTheSameName()
    {
        // The rule was pinned to the standalone box before the tab existed.
        // Keeping the pin would keep filling the box the user just emptied.
        var tab = new DesktopBoxTab { Title = "图片" };
        var aggregate = new DesktopBox { Title = "资料", ManualTabs = [tab] };
        var pinned = new DesktopBox { Title = "图片", IsAutoGenerated = true };
        var state = new CrabDeskState { Boxes = [pinned, aggregate] };

        var target = BoxCategoryResolver.Resolve(state, "图片", pinned.Id);

        Assert.Same(aggregate, target!.Box);
        Assert.Equal(tab.Id, target.TabId);
    }

    [Fact]
    public void LegacyUserTargetWinsOverAnUnrelatedMatchingTab()
    {
        var chosen = new DesktopBox { Title = "工作资料" };
        var other = new DesktopBox { Title = "个人", ManualTabs = [new DesktopBoxTab { Title = "图片" }] };

        Assert.Same(chosen, BoxCategoryResolver.Resolve(new[] { chosen, other }, "图片", chosen.Id)!.Box);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void ExplicitTargetWinsEvenWhenItIsAnAutomaticallyGeneratedBox(bool sameTitle)
    {
        var chosen = new DesktopBox { Title = sameTitle ? "图片" : "工作资料", IsAutoGenerated = true };
        var other = new DesktopBox { Title = "个人", ManualTabs = [new DesktopBoxTab { Title = "图片" }] };
        var rule = new OrganizationRule { Title = "图片", TargetBoxId = chosen.Id, TargetBoxIsExplicit = true };

        Assert.Same(chosen, BoxCategoryResolver.ResolveRule(new[] { chosen, other }, rule)!.Box);
    }

    [Fact]
    public void AutomaticBindingFollowsAnExistingChildTab()
    {
        var chosen = new DesktopBox { Title = "图片" };
        var tab = new DesktopBoxTab { Title = "图片" };
        var other = new DesktopBox { Title = "个人", ManualTabs = [tab] };
        var rule = new OrganizationRule { Title = "图片", TargetBoxId = chosen.Id, TargetBoxIsExplicit = false };

        var target = BoxCategoryResolver.ResolveRule(new[] { chosen, other }, rule)!;

        Assert.Same(other, target.Box);
        Assert.Equal(tab.Id, target.TabId);
    }

    [Fact]
    public void CategoryNamingABoxResolvesToTheBoxWithoutATab()
    {
        var box = new DesktopBox { Title = "图片", ManualTabs = [new DesktopBoxTab { Title = "截图" }] };
        var state = new CrabDeskState { Boxes = [box] };

        var target = BoxCategoryResolver.Resolve(state, "图片");

        Assert.NotNull(target);
        Assert.Same(box, target!.Box);
        Assert.Null(target.TabId);
        Assert.Equal(BoxCategoryMatch.Title, target.Match);
    }

    [Fact]
    public void PinnedBoxWinsOverATitleMatch()
    {
        var chosen = new DesktopBox { Title = "资料" };
        var sameTitle = new DesktopBox { Title = "图片" };
        var state = new CrabDeskState { Boxes = [sameTitle, chosen] };

        Assert.Same(chosen, BoxCategoryResolver.Resolve(state, "图片", chosen.Id)!.Box);
    }

    [Fact]
    public void GeneratedBoxIsPreferredAmongEqualTitleMatches()
    {
        var userBox = new DesktopBox { Title = "图片" };
        var generated = new DesktopBox { Title = "图片", IsAutoGenerated = true };
        var state = new CrabDeskState { Boxes = [userBox, generated] };

        Assert.Same(generated, BoxCategoryResolver.Resolve(state, "图片")!.Box);
    }

    [Fact]
    public void GeneratedBoxIsPreferredAmongEqualChildTabMatches()
    {
        var first = new DesktopBox { Title = "甲", ManualTabs = [new DesktopBoxTab { Title = "图片" }] };
        var second = new DesktopBox
        {
            Title = "乙", IsAutoGenerated = true,
            ManualTabs = [new DesktopBoxTab { Title = "图片" }]
        };
        var state = new CrabDeskState { Boxes = [first, second] };

        Assert.Same(second, BoxCategoryResolver.Resolve(state, "图片")!.Box);
    }

    [Theory]
    [InlineData("  图片  ")]
    [InlineData("图片")]
    public void ChildTabMatchIgnoresSurroundingWhitespace(string category)
    {
        var tab = new DesktopBoxTab { Title = "  图片 " };
        var box = new DesktopBox { Title = "资料", ManualTabs = [tab] };
        var state = new CrabDeskState { Boxes = [box] };

        Assert.Equal(tab.Id, BoxCategoryResolver.Resolve(state, category)!.TabId);
    }

    [Fact]
    public void MappedFolderIsNeverAChildTabTarget()
    {
        var mapped = new DesktopBox
        {
            Title = "镜像",
            MappedFolder = new MappedFolderSettings { Path = "C:\\Mirror" },
            ManualTabs = [new DesktopBoxTab { Title = "图片" }]
        };
        var state = new CrabDeskState { Boxes = [mapped] };

        Assert.Null(BoxCategoryResolver.Resolve(state, "图片"));
    }

    [Fact]
    public void UnknownOrBlankCategoryResolvesToNothing()
    {
        var state = new CrabDeskState { Boxes = [new DesktopBox { Title = "图片" }] };

        Assert.Null(BoxCategoryResolver.Resolve(state, "文档"));
        Assert.Null(BoxCategoryResolver.Resolve(state, "   "));
        Assert.Null(BoxCategoryResolver.Resolve(state, null));
    }

    [Fact]
    public void StalePinFallsBackToATitleMatch()
    {
        var box = new DesktopBox { Title = "图片" };
        var state = new CrabDeskState { Boxes = [box] };

        Assert.Same(box, BoxCategoryResolver.Resolve(state, "图片", Guid.NewGuid())!.Box);
    }
}
